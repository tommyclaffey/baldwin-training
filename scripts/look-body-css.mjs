// The coded screens' text face for looks painted from their roles (Nov 17: J.Baldwin's body is Montserrat). styles.css
// names 'Archivo' in ~170 rules, written for The Baldwin and Mise. Rather than touch those rules (The Baldwin and Mise must
// stay pixel-identical), this writes one block of `.look-roles <selector> { font-family: var(--look-body) }` for every rule
// that sets Archivo, inside the same @media, between the markers in styles.css. --look-body comes from the look
// (theme.ts legacyTokens), so a new look needs nothing here; only a new Archivo rule does.
//   node scripts/look-body-css.mjs          rewrite the block
//   node scripts/look-body-css.mjs --check  exit 1 if the block is out of date (test/store-looks.test.mjs runs this)
import fs from 'node:fs';
import path from 'node:path';

const FILE = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'styles.css');
const START = '/* ── look-body: generated by scripts/look-body-css.mjs, do not edit by hand ── */';
const END = '/* ── end look-body ── */';

export function build(css) {
  const a = css.indexOf(START), b = css.indexOf(END);
  const src = a >= 0 && b > a ? css.slice(0, a) + css.slice(b + END.length) : css;
  const out = [];
  // walk the top level: plain rules and one level of @media
  const noComments = src.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  const rules = (text, media) => {
    let j = 0;
    while (j < text.length) {
      const open = text.indexOf('{', j);
      if (open < 0) break;
      const head = text.slice(j, open).trim();
      if (head.startsWith('@media')) {
        let depth = 1, k = open + 1;
        while (k < text.length && depth) { if (text[k] === '{') depth++; else if (text[k] === '}') depth--; k++; }
        rules(text.slice(open + 1, k - 1), head);
        j = k; continue;
      }
      if (head.startsWith('@')) { // @keyframes, @font-face, @page…: skip the whole block
        let depth = 1, k = open + 1;
        while (k < text.length && depth) { if (text[k] === '{') depth++; else if (text[k] === '}') depth--; k++; }
        j = k; continue;
      }
      const close = text.indexOf('}', open);
      const body = text.slice(open + 1, close);
      if (/(^|;)\s*font(-family)?\s*:[^;]*'Archivo'/.test(body)) {
        const sels = head.split(/,(?![^(]*\))/).map((s) => s.trim()).filter((s) => s && !s.startsWith('.brand-mise') && !s.startsWith('.look-roles'));
        if (sels.length) out.push({ media, sel: sels.map((s) => (/^(html|:root)\b/.test(s) ? s.replace(/^(html|:root)/, 'html.look-roles') : '.look-roles ' + s)).join(', ') });
      }
      j = close + 1;
    }
  };
  rules(noComments, null);
  void i;
  const lines = [START];
  for (const r of out) lines.push(r.media ? `${r.media} { ${r.sel} { font-family: var(--look-body); } }` : `${r.sel} { font-family: var(--look-body); }`);
  lines.push(END);
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const css = fs.readFileSync(FILE, 'utf8');
  const block = build(css);
  const a = css.indexOf(START), b = css.indexOf(END);
  if (process.argv.includes('--check')) {
    const now = a >= 0 && b > a ? css.slice(a, b + END.length) : '';
    if (now !== block) { console.error('styles.css: the look-body block is out of date. Run node scripts/look-body-css.mjs'); process.exit(1); }
    console.log('look-body block is current'); process.exit(0);
  }
  const anchor = '/* ── Looks painted from their roles';
  let next;
  if (a >= 0 && b > a) next = css.slice(0, a) + block + css.slice(b + END.length);
  else { const at = css.indexOf(anchor); next = css.slice(0, at) + block + '\n\n' + css.slice(at); }
  fs.writeFileSync(FILE, next);
  console.log(`wrote ${block.split('\n').length - 2} rules`);
}
